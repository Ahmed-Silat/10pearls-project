-- Every table gets an auto-increment integer primary key named <table in singular>_id, followed by a
-- "uuid" column that keeps the old UUID primary key. Foreign keys now point at the integer keys.
--
-- PostgreSQL cannot change a primary key's type or move a column in place, so each table is rebuilt:
-- create the new table, copy the rows (mapping old foreign keys to the new integer keys),
-- drop the old table and rename the new one. Flyway runs this in a single transaction.
--
-- Old ids are not always bare UUIDs (seeded contacts look like "seed-<uuid>"), so the UUID is extracted
-- from the old id, and a new one is generated when it contains none. Foreign keys are matched on the
-- old id string, kept in a temporary old_id column until the end.

-- users ------------------------------------------------------------------------------------------

CREATE TABLE users_new (
    user_id    BIGINT GENERATED BY DEFAULT AS IDENTITY,
    uuid       UUID         NOT NULL DEFAULT gen_random_uuid(),
    first_name VARCHAR(255),
    last_name  VARCHAR(255),
    email      VARCHAR(255) NOT NULL,
    password   VARCHAR(255) NOT NULL,
    phone      VARCHAR(255),
    address    VARCHAR(255),
    old_id     VARCHAR(255) NOT NULL,
    CONSTRAINT pk_users PRIMARY KEY (user_id),
    CONSTRAINT uk_users_uuid UNIQUE (uuid),
    CONSTRAINT uk_users_email_new UNIQUE (email)
);

INSERT INTO users_new (uuid, first_name, last_name, email, password, phone, address, old_id)
SELECT COALESCE(substring(id FROM '[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}')::uuid,
                gen_random_uuid()),
       first_name, last_name, email, password, phone, address, id
FROM users
ORDER BY email;

-- contacts ---------------------------------------------------------------------------------------

CREATE TABLE contacts_new (
    contact_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    uuid       UUID   NOT NULL DEFAULT gen_random_uuid(),
    first_name VARCHAR(255),
    last_name  VARCHAR(255),
    email      VARCHAR(255),
    phone      VARCHAR(255),
    address    VARCHAR(255),
    user_id    BIGINT NOT NULL,
    CONSTRAINT pk_contacts PRIMARY KEY (contact_id),
    CONSTRAINT uk_contacts_uuid UNIQUE (uuid),
    CONSTRAINT fk_contacts_user_new FOREIGN KEY (user_id) REFERENCES users_new (user_id)
);

INSERT INTO contacts_new (uuid, first_name, last_name, email, phone, address, user_id)
SELECT COALESCE(substring(c.id FROM '[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}')::uuid,
                gen_random_uuid()),
       c.first_name, c.last_name, c.email, c.phone, c.address, u.user_id
FROM contacts c
JOIN users_new u ON u.old_id = c.user_id
ORDER BY u.user_id, c.first_name, c.last_name;

-- password_reset_otps ----------------------------------------------------------------------------

CREATE TABLE password_reset_otps_new (
    password_reset_otp_id  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    uuid                   UUID                        NOT NULL DEFAULT gen_random_uuid(),
    user_id                BIGINT                      NOT NULL,
    otp_hash               VARCHAR(255),
    otp_expires_at         TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    failed_attempts        INTEGER                     NOT NULL,
    reset_token_hash       VARCHAR(255),
    reset_token_expires_at TIMESTAMP(6) WITH TIME ZONE,
    created_at             TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_password_reset_otps PRIMARY KEY (password_reset_otp_id),
    CONSTRAINT uk_password_reset_otps_uuid UNIQUE (uuid),
    CONSTRAINT uk_password_reset_otps_user_new UNIQUE (user_id),
    CONSTRAINT fk_password_reset_otps_user_new FOREIGN KEY (user_id) REFERENCES users_new (user_id)
);

INSERT INTO password_reset_otps_new (uuid, user_id, otp_hash, otp_expires_at, failed_attempts,
                                     reset_token_hash, reset_token_expires_at, created_at)
SELECT COALESCE(substring(p.id FROM '[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}')::uuid,
                gen_random_uuid()),
       u.user_id, p.otp_hash, p.otp_expires_at, p.failed_attempts,
       p.reset_token_hash, p.reset_token_expires_at, p.created_at
FROM password_reset_otps p
JOIN users_new u ON u.old_id = p.user_id;

-- swap the new tables in -------------------------------------------------------------------------

DROP TABLE password_reset_otps;
DROP TABLE contacts;
DROP TABLE users;

ALTER TABLE users_new DROP COLUMN old_id;
ALTER TABLE users_new RENAME TO users;
ALTER TABLE users RENAME CONSTRAINT uk_users_email_new TO uk_users_email;
ALTER SEQUENCE users_new_user_id_seq RENAME TO users_user_id_seq;

ALTER TABLE contacts_new RENAME TO contacts;
ALTER TABLE contacts RENAME CONSTRAINT fk_contacts_user_new TO fk_contacts_user;
ALTER SEQUENCE contacts_new_contact_id_seq RENAME TO contacts_contact_id_seq;
CREATE INDEX idx_contacts_user_id ON contacts (user_id);

ALTER TABLE password_reset_otps_new RENAME TO password_reset_otps;
ALTER TABLE password_reset_otps RENAME CONSTRAINT uk_password_reset_otps_user_new TO uk_password_reset_otps_user;
ALTER TABLE password_reset_otps RENAME CONSTRAINT fk_password_reset_otps_user_new TO fk_password_reset_otps_user;
ALTER SEQUENCE password_reset_otps_new_password_reset_otp_id_seq RENAME TO password_reset_otps_password_reset_otp_id_seq;
