-- Groups / tags: each user has their own tags (Family, Work, ...) and a contact can have several.

CREATE TABLE tags (
    tag_id     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    uuid       UUID         NOT NULL DEFAULT gen_random_uuid(),
    user_id    BIGINT       NOT NULL,
    name       VARCHAR(30)  NOT NULL,
    color      VARCHAR(20)  NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT pk_tags PRIMARY KEY (tag_id),
    CONSTRAINT uk_tags_uuid UNIQUE (uuid),
    CONSTRAINT fk_tags_user FOREIGN KEY (user_id) REFERENCES users (user_id) ON DELETE CASCADE
);

-- One tag per name per user, ignoring case ("Work" and "work" are the same tag).
CREATE UNIQUE INDEX uk_tags_user_name ON tags (user_id, lower(name));

-- Which contacts have which tags. Deleting a contact (for good) or a tag removes its rows here.
CREATE TABLE contact_tags (
    contact_id BIGINT NOT NULL,
    tag_id     BIGINT NOT NULL,
    CONSTRAINT pk_contact_tags PRIMARY KEY (contact_id, tag_id),
    CONSTRAINT fk_contact_tags_contact FOREIGN KEY (contact_id) REFERENCES contacts (contact_id) ON DELETE CASCADE,
    CONSTRAINT fk_contact_tags_tag FOREIGN KEY (tag_id) REFERENCES tags (tag_id) ON DELETE CASCADE
);

-- For "contacts with this tag" (the tag filter and the counts).
CREATE INDEX idx_contact_tags_tag_id ON contact_tags (tag_id);
